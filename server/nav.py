"""Routing and spoken guidance. Distances are meters, angles clockwise degrees.

Map x points right and y points down. The map is generated by demo/build_model.py.
"""
import heapq
import json
import math
import re
import time
from pathlib import Path

MAP_PATH = Path(__file__).parent.parent / "demo" / "grady-ground.json"
STOP_M = 1.0  # Center obstacle closer than this stops the walker.
ARRIVE_M = 1.2  # Marker closer than this means the node is reached.
ANCHOR_M = 2.0  # Closer markers skip heading anchoring: a small sideways offset skews their bearing.
TURN_DEG = 15  # Heading error above this needs a turn instruction.
REPEAT_S = 3.0  # The same kind of line waits this long before speaking again.
LEG_S_PER_STEP = 2.5  # A leg running longer than this per step means the marker was missed.
SIGHTED_S = 8.0  # Seeing the next marker allows at least this much more walking time.
QUIET = {"speak": None, "alert": "none"}


def turn_text(error):
    side = "right" if error > 0 else "left"
    return f"Turn {side} about {round(abs(error) / 5) * 5} degrees."


class Navigator:
    def __init__(self, map_path=MAP_PATH, clock=time.monotonic):
        data = json.loads(Path(map_path).read_text(encoding="utf8"))
        self.nodes = data["nodes"]
        self.clock = clock
        self.graph = {node: {} for node in self.nodes}
        for a, b, steps in data["edges"]:
            self.graph[a][b] = self.graph[b][a] = steps
        self.by_marker = {n["marker"]: key for key, n in self.nodes.items()}
        self.aliases = sorted(
            ((alias, key) for key, n in self.nodes.items() for alias in n["aliases"]),
            key=lambda item: -len(item[0]),
        )
        self.node = "entrance"
        self.route = []  # Node ids from the current node to the destination.
        self.heading = None  # Latest phone heading.
        self.offset = None  # Add to the phone heading to get the map heading.
        self.announced = False  # This leg's walk line has been spoken.
        self.interrupted = False  # A turn or stop since then needs a line to resume.
        self.deadline = None  # When this leg should have ended, once walking starts.
        self.last_line = None
        self.said_at = {}

    def state(self):
        return {
            "node": self.node,
            "marker": self.nodes[self.node]["marker"],
            "destination": self.route[-1] if self.route else None,
        }

    def command(self, text):
        text = text.lower()
        if re.search(r"\bwhere am i\b", text):
            return self._where()
        if re.search(r"\brepeat\b", text):
            return self.last_line or "Nothing to repeat yet."
        if re.search(r"\bcancel\b", text):
            self.route = []
            return self._speak("cancel", "Route cancelled.")
        if re.search(r"\bstop\b", text):
            self.route = []
            return self._speak("cancel", "Stopped. Tell me where you want to go when you are ready.")
        for alias, key in self.aliases:
            if re.search(rf"\b{re.escape(alias)}\b", text):
                return self._start(key)
        places = ", ".join(self.nodes[key]["name"] for key, n in self.nodes.items() if n["aliases"])
        return self._speak("unknown", f"Sorry, I did not catch that. You can go to: {places}.")

    def update(self, perception, heading):
        self.heading = heading
        if self.offset is None:
            self.offset = self.nodes[self.node]["facing"] - heading
        arrived = self._read_markers(perception["markers"], heading)
        if arrived:
            return {"speak": self._speak("arrived", arrived), "alert": "none"}
        if not self.route:
            return QUIET
        if not perception["view_ok"]:
            return self._say("view", "Camera blocked. Hold the phone flat against your chest.", "warn")
        error = self._heading_error()
        obstacles = perception["obstacles"]
        if obstacles["center"] < STOP_M:
            return self._say("obstacle", self._obstacle_text(obstacles, error), "stop")
        if self.deadline is not None and self.clock() > self.deadline:
            return self._say("lost", "Stop. I cannot find the next sign. Turn slowly until I see it.", "stop")
        line = self._next_line(error)
        return self._say(*line) if line else QUIET

    def _start(self, destination):
        if destination == self.node:
            self.route = []
            return self._speak("arrived", f"You are already at {self.nodes[destination]['name']}.")
        self.route = self._shortest(self.node, destination)
        self._begin_leg()
        key, text = self._next_line(self._heading_error())
        return self._speak(key, f"Starting route to {self.nodes[destination]['name']}. {text}")

    def _where(self):
        name = self.nodes[self.node]["name"]
        if not self.route:
            return f"You are at {name}."
        return f"You are near {name}, heading to {self.nodes[self.route[-1]]['name']}."

    def _read_markers(self, markers, heading):
        """Anchor the heading on the nearest known marker. Returns an arrival line if there is one."""
        known = [m for m in markers if m["id"] in self.by_marker]
        if self.route:
            # The marker just reached can still be in view while walking past it, off to the side.
            known = [m for m in known if self.by_marker[m["id"]] != self.node]
        if not known:
            return None
        nearest = min(known, key=lambda m: m["distance_m"])
        node = self.by_marker[nearest["id"]]
        if nearest["distance_m"] >= ANCHOR_M:
            self.offset = self.nodes[node]["facing"] - nearest["bearing_deg"] - heading
        if self.route and self.deadline is not None and node == self.route[1]:
            self.deadline = max(self.deadline, self.clock() + SIGHTED_S)
        if nearest["distance_m"] >= ARRIVE_M or node == self.node:
            return None
        self.node = node
        if not self.route:
            return None
        destination = self.route[-1]
        if node == destination:
            self.route = []
            return f"You have arrived at {self.nodes[node]['name']}."
        self.route = self._shortest(node, destination)
        self._begin_leg()
        return None

    def _begin_leg(self):
        self.announced = False
        self.interrupted = False
        self.deadline = None

    def _heading_error(self):
        """Clockwise degrees from where the walker faces to the current hallway."""
        if self.heading is None:
            return 0.0
        a, b = (self.nodes[key] for key in self.route[:2])
        hallway = math.degrees(math.atan2(b["x"] - a["x"], -(b["y"] - a["y"])))
        return (hallway - (self.heading + self.offset) + 180) % 360 - 180

    def _next_line(self, error):
        if abs(error) > TURN_DEG:
            return "turn", turn_text(error)
        if not self.announced:
            steps = self.graph[self.route[0]][self.route[1]]
            return "walk", f"Walk forward about {steps} steps."
        if self.interrupted:
            return "keep", "Keep walking."
        return None

    def _obstacle_text(self, obstacles, error):
        if abs(error) > TURN_DEG:
            return f"Stop. Obstacle ahead. {turn_text(error)}"
        side = "left" if obstacles["left"] >= obstacles["right"] else "right"
        return f"Stop. Obstacle ahead. More space on your {side}."

    def _say(self, key, text, alert="none"):
        """Speak unless this kind of line was said in the last few seconds."""
        if self.clock() - self.said_at.get(key, -math.inf) < REPEAT_S:
            return QUIET
        return {"speak": self._speak(key, text), "alert": alert}

    def _speak(self, key, text):
        self.said_at[key] = self.clock()
        self.last_line = text
        if key in ("turn", "obstacle", "lost"):
            self.interrupted = True
        elif key == "walk":
            self.announced = True
            self.interrupted = False
            self.deadline = self.clock() + self.graph[self.route[0]][self.route[1]] * LEG_S_PER_STEP
        elif key == "keep":
            self.interrupted = False
        return text

    def _shortest(self, start, end):
        queue = [(0, start, [start])]
        seen = set()
        while queue:
            steps, node, path = heapq.heappop(queue)
            if node == end:
                return path
            if node not in seen:
                seen.add(node)
                for neighbor, length in self.graph[node].items():
                    heapq.heappush(queue, (steps + length, neighbor, path + [neighbor]))
        raise ValueError(f"No route from {start} to {end}")
